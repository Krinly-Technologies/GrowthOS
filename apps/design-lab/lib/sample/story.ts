const STAGE_TEXT: Record<Stage, string> = {
  new: 'New enquiry',
  contacted: 'Moved to Contacted',
  interested: 'Moved to Interested',
  ready: 'Moved to Ready to book',
  booked: 'Booked',
  lost: 'Marked lost',
};

export function buildStory(): LabData {
  const data: LabData = { leads: [], activities: [], payments: [], bookings: [] };
  for (const spec of SPECS) {
    const { stages, log, payments = [], bookings = [], ...rest } = spec;
    const last = stages[stages.length - 1];
    const lead: Lead = {
      ...rest,
      stage: last ? last[0] : 'new',
      history: stages.map(([stage, at]) => ({ stage, at })),
    };
    data.leads.push(lead);
    log.forEach(([at, kind, by, text, extra], i) => {
      data.activities.push({
        id: `${spec.id}-a${i}`,
        leadId: spec.id,
        at,
        kind,
        by,
        text,
        ...extra,
      });
    });
    stages.slice(1).forEach(([stage, at], i) => {
      const from = stages[i]?.[0];
      if (from === stage) return;
      data.activities.push({
        id: `${spec.id}-s${i}`,
        leadId: spec.id,
        at,
        kind: 'stage',
        by: spec.owner,
        text: STAGE_TEXT[stage],
        ...(from ? { from } : {}),
        to: stage,
      });
    });
    payments.forEach((p, i) => {
      const id = `${spec.id}-p${i}`;
      data.payments.push({ ...p, id, leadId: spec.id });
    });
    bookings.forEach((b, i) => {
      data.bookings.push({ ...b, id: `${spec.id}-b${i}`, leadId: spec.id });
    });
  }
  return data;
}
